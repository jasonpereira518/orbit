import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import ts from "typescript";

/**
 * The `@source` list for `src/app/site.css`: every repo file the marketing pages can render.
 *
 * site.css generates Tailwind utilities ONLY from these files, so a class used by a file
 * missing here silently has no CSS on the marketing pages. The list is therefore the whole
 * import graph of every `(site)` route file and the root-level files that render without a
 * route group (root layout, not-found, global-error) — client components and dynamic
 * `import()`s included, since both render there. Generated (`npm run css:site`) and checked
 * by `smoke-site-css-sources`, never hand-edited.
 */
export const SITE_SOURCES_FILE = "src/app/site-sources.css";

export function siteCssSourceFiles(): string[] {
  const root = resolve(".");
  const entries = execFileSync("find", ["src/app/(site)", "-name", "*.tsx"], { encoding: "utf8" })
    .trim()
    .split("\n")
    .concat(["src/app/layout.tsx", "src/app/not-found.tsx", "src/app/global-error.tsx"]);
  const seen = new Set<string>();
  const queue = entries.map((e) => resolve(e));

  const resolveSpecifier = (from: string, specifier: string): string | null => {
    let base: string;
    if (specifier.startsWith("@/")) base = join(root, "src", specifier.slice(2));
    else if (specifier.startsWith(".")) base = resolve(dirname(from), specifier);
    else return null;
    for (const candidate of [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts"), join(base, "index.tsx")]) {
      if (existsSync(candidate) && /\.tsx?$/.test(candidate)) return candidate;
    }
    return null;
  };

  while (queue.length) {
    const file = queue.pop()!;
    if (seen.has(file)) continue;
    seen.add(file);
    const sf = ts.createSourceFile(
      file,
      readFileSync(file, "utf8"),
      ts.ScriptTarget.Latest,
      true,
      file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS
    );
    const visit = (node: ts.Node) => {
      let specifier: ts.Expression | undefined;
      if (ts.isImportDeclaration(node) && !node.importClause?.isTypeOnly) specifier = node.moduleSpecifier;
      else if (ts.isExportDeclaration(node) && !node.isTypeOnly) specifier = node.moduleSpecifier;
      else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) specifier = node.arguments[0];
      if (specifier && ts.isStringLiteral(specifier)) {
        const resolved = resolveSpecifier(file, specifier.text);
        if (resolved) queue.push(resolved);
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
  return [...seen].map((f) => relative(root, f)).sort();
}

/** The generated file's full text. Paths are relative to src/app, where it lives. */
export function siteCssSourcesText(): string {
  const lines = siteCssSourceFiles().map((f) => `@source "${relative("src/app", f)}";`);
  return [
    "/* GENERATED by `npm run css:site` (scripts/lib/site-css-sources.ts). Do not edit. */",
    "/* Every file the marketing pages render; site.css builds its utilities from these alone. */",
    ...lines,
    "",
  ].join("\n");
}
