/**
 * Generates docs/MCP.md from ORBIT_TOOLS, the one registry behind both the MCP server and
 * Orbit's in-app chat (src/lib/tools/definitions.ts). Never edit docs/MCP.md by hand.
 *
 * Run: npx tsx scripts/gen-mcp-docs.ts           (writes docs/MCP.md)
 *      npx tsx scripts/gen-mcp-docs.ts --check   (exit 1 if docs/MCP.md is stale)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";
import { ORBIT_TOOLS } from "../src/lib/tools/definitions";

type JsonSchema = {
  type?: string | string[];
  enum?: unknown[];
  format?: string;
  default?: unknown;
  description?: string;
  minimum?: number;
  maximum?: number;
  minLength?: number;
  maxLength?: number;
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
};

function typeOf(s: JsonSchema): string {
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" \\| ");
  if (s.anyOf) return s.anyOf.map(typeOf).join(" \\| ");
  const base = Array.isArray(s.type) ? s.type.join(" \\| ") : (s.type ?? "any");
  if (base === "array" && s.items) return `${typeOf(s.items)}[]`;
  return s.format ? `${base} (${s.format})` : base;
}

function constraints(s: JsonSchema): string {
  const out: string[] = [];
  if (s.minimum !== undefined) out.push(`min ${s.minimum}`);
  if (s.maximum !== undefined) out.push(`max ${s.maximum}`);
  if (s.minLength !== undefined) out.push(`min length ${s.minLength}`);
  if (s.maxLength !== undefined) out.push(`max length ${s.maxLength}`);
  if (s.default !== undefined) out.push(`default ${JSON.stringify(s.default)}`);
  return out.join(", ");
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();

function fieldsTable(shape: Parameters<typeof z.object>[0]): string {
  const schema = z.toJSONSchema(z.object(shape), { io: "input", unrepresentable: "any" }) as JsonSchema;
  const props = schema.properties ?? {};
  const names = Object.keys(props);
  if (names.length === 0) return "_No input._\n";
  const required = new Set(schema.required ?? []);
  const rows = names.map((name) => {
    const p = props[name];
    return `| \`${name}\` | ${typeOf(p)} | ${required.has(name) ? "yes" : "no"} | ${cell(constraints(p))} | ${cell(p.description ?? "")} |`;
  });
  return ["| Field | Type | Required | Constraints | Description |", "|---|---|---|---|---|", ...rows, ""].join("\n");
}

const surfaceLabel = (s: readonly string[]) =>
  s.length === 2 ? "MCP and in-app chat" : s[0] === "mcp" ? "MCP only" : "In-app chat only";

function render(): string {
  const lines: string[] = [
    "# MCP and chat tools",
    "",
    "<!-- GENERATED by scripts/gen-mcp-docs.ts from ORBIT_TOOLS. Do not edit by hand. -->",
    "",
    "Orbit's tools are defined once, in [`src/lib/tools/definitions.ts`](../src/lib/tools/definitions.ts), and",
    "offered to two surfaces: the MCP server (`/api/mcp`) and Orbit's own chat. A `write` tool is hidden from a",
    "read-only API key. Read the security comment at the top of `src/lib/mcp/server.ts` before adding a tool:",
    "no tool may send, fetch a URL, register a webhook or approve a draft.",
    "",
    "The REST API is described separately by `GET /api/v1/openapi.json` on any deployment",
    "(source: `src/app/api/v1/openapi.json/route.ts`).",
    "",
    "Regenerate with `npx tsx scripts/gen-mcp-docs.ts`.",
    "",
    `${ORBIT_TOOLS.length} tools.`,
    "",
    "| Tool | Scope | Surface |",
    "|---|---|---|",
    ...ORBIT_TOOLS.map((t) => `| [\`${t.name}\`](#${t.name}) | ${t.scope} | ${surfaceLabel(t.surfaces)} |`),
    "",
  ];
  for (const t of ORBIT_TOOLS) {
    lines.push(`## ${t.name}`, "", `**${t.title}**. Scope: \`${t.scope}\`. Surface: ${surfaceLabel(t.surfaces)}.`, "");
    lines.push(t.description.trim(), "");
    if (t.releasedSurface) lines.push(`Offered only while the \`${t.releasedSurface}\` surface is released to the asker.`, "");
    lines.push(fieldsTable(t.inputSchema));
    if (t.fields) {
      for (const [surface, allow] of Object.entries(t.fields)) {
        lines.push(`Returned fields on ${surface}: ${(allow ?? []).map((f) => `\`${f}\``).join(", ")}.`, "");
      }
    }
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

const out = "docs/MCP.md";
const next = render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (current !== next) {
    console.error(`${out} is stale. Run: npx tsx scripts/gen-mcp-docs.ts`);
    process.exit(1);
  }
  console.log(`${out} is up to date.`);
} else {
  writeFileSync(out, next);
  console.log(`wrote ${out} (${ORBIT_TOOLS.length} tools)`);
}
process.exit(0);
